"""Blueprint -> Plan. Order: preset, features, finalize, project files, user overrides."""

from __future__ import annotations

from .errors import Issue, MakiError, UnsafePathError, errors
from .paths import normalize
from .plan import Plan
from .registry import FEATURES, PRESETS, load_all
from .schema import Blueprint
from .templating import render
from .validate import derive_apps, effective_features, validate_blueprint, validate_plan

README = """# {{ project.name }}

{{ project.description }}

Generated by Maki. See `docs/setup.md` if present.

{% for a in apps %}
- `{{ a.root or "." }}`: {{ a.framework }}
{% endfor %}
"""

GITIGNORE = ".env\n.venv/\n__pycache__/\n*.pyc\nnode_modules/\ndist/\n*.db\n.pytest_cache/\n.ruff_cache/\n.mypy_cache/\n"

STARTERS = {".py": '"""TODO."""\n', ".md": "# TODO\n", ".json": "{}\n", ".ts": "export {};\n",
            ".tsx": "export {};\n", ".html": "<!doctype html>\n"}


def _order(feats: dict[str, dict]) -> list[str]:
    done: list[str] = []
    pending = list(feats)
    while pending:
        progressed = False
        for fid in list(pending):
            reqs = FEATURES[fid].requires if fid in FEATURES else ()
            if all(r in done or r not in feats for r in reqs):
                done.append(fid)
                pending.remove(fid)
                progressed = True
        if not progressed:
            done.extend(pending)
            break
    return done


def build_plan(bp: Blueprint) -> tuple[Plan, list[Issue]]:
    """Never touches disk. Returns the Plan and every issue found."""
    load_all()
    plan = Plan()
    issues = validate_blueprint(bp)
    if errors(issues):
        return plan, issues
    feats = effective_features(bp)
    plan.features = feats
    plan.apps = derive_apps(bp)
    plan.base_ctx = {"project": bp.project, "blueprint": bp, "apps": plan.apps, "var": bp.variables}
    order = [f for f in _order(feats) if f in FEATURES]
    if bp.deployment != "none" and "docker" not in bp.features:
        plan.notes.append(f"deployment={bp.deployment!r} added the 'docker' feature")
    try:
        for app in plan.apps:
            preset = PRESETS[app.framework]
            preset.build(plan.scoped(app, f"preset:{preset.id}"))
            for fid in order:
                f = FEATURES[fid]
                if f.scope == "app" and f.applies_to(app):
                    f.apply(plan.scoped(app, f"feature:{fid}", feats[fid]))
            preset.finalize(plan.scoped(app, f"preset:{preset.id}"))
        core = plan.scoped(None, "core")
        core.put("README.md", README)
        core.put(".gitignore", GITIGNORE, templ=False)
        for fid in order:
            f = FEATURES[fid]
            if f.scope == "project":
                f.apply(plan.scoped(None, f"feature:{fid}", feats[fid]))
        for root, env in plan.env.items():
            body = "".join((f"# {c}\n" if c else "") + f"{k}={v}\n" for k, (v, c) in env.items())
            plan.put(f"{root}/.env.example" if root else ".env.example", body, "core")
        apply_overrides(plan, bp)
    except MakiError as exc:
        issues.append(Issue("error", "build-failed", str(exc)))
        return plan, issues
    return plan, issues + validate_plan(plan)


def _within(path: str, prefix: str) -> bool:
    return path == prefix or path.startswith(prefix + "/")


def apply_overrides(plan: Plan, bp: Blueprint) -> None:
    def bad(code: str, msg: str, path: str | None = None) -> None:
        plan.issues.append(Issue("error", code, msg, path))

    for ov in bp.overrides:
        try:
            path = normalize(ov.path)
            if ov.op == "add":
                if ov.path.endswith("/"):
                    plan.dirs[path] = "user"
                elif path in plan.entries:
                    bad("override", f"add: {path} already exists (use set_content)", path)
                else:
                    plan.put(path, _content(plan, ov, path), "user")
            elif ov.op == "set_content":
                e = plan.entries.get(path)
                if e is None:
                    bad("override", f"set_content: {path} does not exist", path)
                elif ov.mode != "preset":
                    e.history.append(e.origin)
                    e.content, e.origin = _content(plan, ov, path), "user"
            elif ov.op == "remove":
                hit = [p for p in plan.entries if _within(p, path)]
                hit_dirs = [d for d in plan.dirs if _within(d, path)]
                for p in hit:
                    del plan.entries[p]
                for d in hit_dirs:
                    del plan.dirs[d]
                if not hit and not hit_dirs:
                    plan.issues.append(Issue("warning", "override", f"remove: nothing matched {path}", path))
            elif ov.op == "move":
                if not ov.to:
                    bad("override", "move needs `to`", path)
                    continue
                dest = normalize(ov.to)
                hit = [p for p in plan.entries if _within(p, path)]
                hit_dirs = [d for d in plan.dirs if _within(d, path)]
                if not hit and not hit_dirs:
                    bad("override", f"move: nothing matched {path}", path)
                    continue
                if dest == path:
                    continue
                if _within(dest, path):
                    bad("override", f"move: {dest} cannot be moved inside itself", dest)
                    continue
                moved_entries = {p: dest + p[len(path):] for p in hit}
                moved_dirs = {d: dest + d[len(path):] for d in hit_dirs}
                entry_collisions = [
                    new for source, new in moved_entries.items()
                    if new in plan.entries and new not in moved_entries
                ]
                dir_collisions = [
                    new for source, new in moved_dirs.items()
                    if new in plan.dirs and new not in moved_dirs
                ]
                if entry_collisions or dir_collisions:
                    collision = (entry_collisions + dir_collisions)[0]
                    bad("override", f"move: {collision} already exists", collision)
                    continue
                for p, new in moved_entries.items():
                    e = plan.entries.pop(p)
                    if e.origin != "user":
                        plan.issues.append(Issue("warning", "moved-owned-file",
                                                 f"{p} is owned by {e.origin}; imports/config that reference it may break", p))
                    e.history.append(e.origin)
                    e.path = new
                    plan.entries[new] = e
                for d, new in moved_dirs.items():
                    plan.dirs[new] = plan.dirs.pop(d)
        except UnsafePathError as exc:
            bad("unsafe-path", str(exc), ov.path)


def _content(plan: Plan, ov, path: str) -> str:
    if ov.mode == "empty":
        return ""
    if ov.mode == "starter":
        return STARTERS.get("." + path.rsplit(".", 1)[-1], "") if "." in path.rsplit("/", 1)[-1] else ""
    if ov.content is None:
        raise UnsafePathError(f"{path}: mode 'custom' needs `content`")
    return render(ov.content, plan.base_ctx, where=f"override:{path}") if ov.render else ov.content
